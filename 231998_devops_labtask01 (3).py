# ==============================================================================
# EMPLOYEE ATTRITION PREDICTION PROJECT
# ------------------------------------------------------------------------------
# Goal: Predict whether an employee will leave the company (Attrition = Yes/No)
# using two machine learning algorithms, then compare which one performs better.
#
# Algorithms used:
#   1) Logistic Regression  -> a simple, fast, and very interpretable model
#   2) Random Forest        -> a stronger model made of many decision trees
#
# Steps followed (this is the standard Data Science workflow):
#   1. Load the data
#   2. Clean and prepare the data (handle text columns, remove useless columns)
#   3. Split data into training (80%) and testing (20%) sets
#   4. Train both models on the training data
#   5. Test both models on unseen testing data
#   6. Compare their performance using Accuracy, Precision, Recall, F1, ROC-AUC
#   7. Draw charts to visualize everything
# ==============================================================================

# ------------------------------------------------------------------------------
# STEP 0: IMPORT ALL THE LIBRARIES WE NEED
# ------------------------------------------------------------------------------
import pandas as pd                        # for loading and handling table data (DataFrames)
import numpy as np                          # for numeric operations
import matplotlib.pyplot as plt             # for drawing charts
import seaborn as sns                       # for nicer looking charts (built on matplotlib)

from sklearn.model_selection import train_test_split   # to split data into train/test
from sklearn.preprocessing import LabelEncoder, StandardScaler  # to prepare the data
from sklearn.linear_model import LogisticRegression    # Algorithm 1
from sklearn.ensemble import RandomForestClassifier    # Algorithm 2
from sklearn.metrics import (                          # tools to measure how good our models are
    accuracy_score, precision_score, recall_score,
    f1_score, roc_auc_score, roc_curve, confusion_matrix
)

# Set a fixed "seed" so that random operations (splitting, sampling, training)
# always give the SAME result every time we run the code. This makes our
# results reproducible instead of changing randomly each run.
RANDOM_STATE = 42

# Make the charts look clean and professional
sns.set_style("whitegrid")
plt.rcParams["figure.dpi"] = 110

# ------------------------------------------------------------------------------
# STEP 1: LOAD THE DATASET
# ------------------------------------------------------------------------------
# Read the CSV file into a pandas DataFrame (a table, like an Excel sheet)
full_data = pd.read_csv("WA_Fn-UseC_-HR-Employee-Attrition.csv")

print("Original dataset shape (rows, columns):", full_data.shape)

# The task requires exactly 500 rows. The original file has 1470 rows, so we
# take a random sample of 500 rows. We use "stratified" sampling on the target
# column (Attrition) so the 500 rows keep the SAME Yes/No ratio as the full
# dataset -> this keeps our smaller dataset realistic instead of biased.
data_500, _ = train_test_split(
    full_data,
    train_size=500,                 # exactly 500 rows kept
    stratify=full_data["Attrition"],# keep the same class balance
    random_state=RANDOM_STATE
)
data_500 = data_500.reset_index(drop=True)   # reset row numbers to 0,1,2,...

print("Sampled dataset shape (rows, columns):", data_500.shape)

# ------------------------------------------------------------------------------
# STEP 2: DATA CLEANING
# ------------------------------------------------------------------------------
# Check for missing (empty) values in every column
print("\nMissing values in each column:\n", data_500.isnull().sum().sum(), "total missing values")
# (This dataset is known to be clean, but we check anyway - good practice!)

# Some columns carry NO useful information because every employee has the same
# value in them (they never change), so they cannot help us predict anything.
# We remove these 4 columns:
#   - EmployeeCount     -> always 1 for every row
#   - EmployeeNumber    -> just an ID number, not a real feature
#   - Over18            -> always "Y" for every row
#   - StandardHours     -> always 80 for every row
useless_columns = ["EmployeeCount", "EmployeeNumber", "Over18", "StandardHours"]
data = data_500.drop(columns=useless_columns)

print("\nColumns removed (no useful information):", useless_columns)
print("Remaining feature columns (30 features + 1 target):", data.shape[1])

# ------------------------------------------------------------------------------
# STEP 3: SEPARATE TARGET (WHAT WE WANT TO PREDICT) FROM FEATURES
# ------------------------------------------------------------------------------
# Our target column is "Attrition" -> it says if an employee left ("Yes") or
# stayed ("No"). We convert it into numbers: Yes -> 1, No -> 0
target_encoder = LabelEncoder()
y = target_encoder.fit_transform(data["Attrition"])   # y is now 0s and 1s

# X holds all the other 30 columns -> these are our "features" (the clues we
# use to make the prediction)
X = data.drop(columns=["Attrition"])

print("\nFeature matrix (X) shape:", X.shape)
print("Target (y) shape:", y.shape)
print("Attrition class balance -> 0 = Stayed, 1 = Left:")
print(pd.Series(y).value_counts())

# ------------------------------------------------------------------------------
# STEP 4: ENCODE CATEGORICAL (TEXT) COLUMNS INTO NUMBERS
# ------------------------------------------------------------------------------
# Machine learning models only understand numbers, not text like "Male" or
# "Sales". So we convert every text column into numeric form.

# First, find which columns contain text (categorical data)
categorical_columns = X.select_dtypes(include=["object", "string"]).columns.tolist()
print("\nText (categorical) columns that need encoding:", categorical_columns)

# We use "one-hot encoding": each category becomes its own 0/1 column.
# Example: "Department" (Sales/HR/R&D) becomes 3 columns of 0s and 1s.
# This is simple, beginner-friendly, and avoids tricking the model into
# thinking categories have a numeric order (e.g. that "R&D" > "Sales").
X_encoded = pd.get_dummies(X, columns=categorical_columns, drop_first=True)

print("Shape after encoding text columns into numbers:", X_encoded.shape)

# ------------------------------------------------------------------------------
# STEP 5: SPLIT DATA INTO TRAINING (80%) AND TESTING (20%) SETS
# ------------------------------------------------------------------------------
# We train the model on 80% of the data, and keep 20% completely hidden from
# training so we can fairly test how well the model performs on NEW data.
X_train, X_test, y_train, y_test = train_test_split(
    X_encoded, y,
    test_size=0.20,                 # 20% for testing
    stratify=y,                     # keep the same Yes/No ratio in both sets
    random_state=RANDOM_STATE
)

print("\nTraining set size:", X_train.shape[0], "rows")
print("Testing set size:", X_test.shape[0], "rows")

# ------------------------------------------------------------------------------
# STEP 6: FEATURE SCALING
# ------------------------------------------------------------------------------
# Columns like "MonthlyIncome" (thousands) and "Education" (1-5) are on very
# different scales. Logistic Regression works better when every column is on
# a similar scale, so we standardize the numbers (mean = 0, std = 1).
# IMPORTANT: we "fit" the scaler ONLY on training data, then apply it to both
# train and test. This prevents "data leakage" (test data influencing training).
scaler = StandardScaler()
X_train_scaled = scaler.fit_transform(X_train)   # learn + apply on train data
X_test_scaled = scaler.transform(X_test)         # only apply (using train's rules) on test data

# ------------------------------------------------------------------------------
# STEP 7: TRAIN ALGORITHM 1 -> LOGISTIC REGRESSION
# ------------------------------------------------------------------------------
# Logistic Regression is a simple, well-known algorithm for Yes/No predictions.
# class_weight="balanced" tells the model to pay extra attention to the
# smaller class (employees who left), since fewer people leave than stay.
log_reg_model = LogisticRegression(
    class_weight="balanced",
    max_iter=1000,          # allow enough iterations for the model to fully learn
    random_state=RANDOM_STATE
)
log_reg_model.fit(X_train_scaled, y_train)   # train the model

# Make predictions on the unseen test data
log_reg_predictions = log_reg_model.predict(X_test_scaled)
log_reg_probabilities = log_reg_model.predict_proba(X_test_scaled)[:, 1]  # probability of "Left"

# ------------------------------------------------------------------------------
# STEP 8: TRAIN ALGORITHM 2 -> RANDOM FOREST
# ------------------------------------------------------------------------------
# Random Forest builds many small decision trees and lets them "vote" on the
# final answer. It usually captures more complex patterns than a single model.
# We deliberately keep the trees shallow (max_depth=5) and limit their size
# (min_samples_leaf=4) so the model learns general patterns instead of
# memorizing the training data -> this helps AVOID OVERFITTING.
random_forest_model = RandomForestClassifier(
    n_estimators=200,        # number of trees in the forest
    max_depth=4,             # limit tree depth -> keeps the model simple, avoids overfitting
    min_samples_leaf=6,      # each leaf must have at least 6 samples -> smoother, more general rules
    class_weight="balanced", # give extra weight to the minority ("Left") class
    random_state=RANDOM_STATE
)
random_forest_model.fit(X_train_scaled, y_train)   # train the model

# Make predictions on the unseen test data
rf_predictions = random_forest_model.predict(X_test_scaled)
rf_probabilities = random_forest_model.predict_proba(X_test_scaled)[:, 1]  # probability of "Left"

# ------------------------------------------------------------------------------
# STEP 9: CHECK FOR OVERFITTING
# ------------------------------------------------------------------------------
# Overfitting means a model memorizes the training data but fails on new data.
# We detect this by comparing TRAIN accuracy vs TEST accuracy.
# If train accuracy is MUCH higher than test accuracy, the model overfitted.
log_reg_train_acc = accuracy_score(y_train, log_reg_model.predict(X_train_scaled))
log_reg_test_acc = accuracy_score(y_test, log_reg_predictions)

rf_train_acc = accuracy_score(y_train, random_forest_model.predict(X_train_scaled))
rf_test_acc = accuracy_score(y_test, rf_predictions)

print("\n--- Overfitting Check (Train accuracy vs Test accuracy) ---")
print(f"Logistic Regression -> Train: {log_reg_train_acc:.3f} | Test: {log_reg_test_acc:.3f}")
print(f"Random Forest        -> Train: {rf_train_acc:.3f} | Test: {rf_test_acc:.3f}")
print("(A small gap between Train and Test accuracy means the model generalizes well.)")

# ------------------------------------------------------------------------------
# STEP 10: CALCULATE PERFORMANCE METRICS FOR BOTH MODELS
# ------------------------------------------------------------------------------
# We use "weighted" averaging for precision/recall/f1 because our classes are
# imbalanced (more people stay than leave) - weighted averaging gives a fair,
# realistic overall score that accounts for both classes properly.
def evaluate_model(y_true, y_pred, y_prob, model_name):
    """Calculate and return the 5 key performance metrics for a model."""
    results = {
        "Model": model_name,
        "Accuracy": accuracy_score(y_true, y_pred),
        "Precision": precision_score(y_true, y_pred, average="weighted", zero_division=0),
        "Recall": recall_score(y_true, y_pred, average="weighted", zero_division=0),
        "F1-Score": f1_score(y_true, y_pred, average="weighted", zero_division=0),
        "ROC-AUC": roc_auc_score(y_true, y_prob)
    }
    return results

log_reg_results = evaluate_model(y_test, log_reg_predictions, log_reg_probabilities, "Logistic Regression")
rf_results = evaluate_model(y_test, rf_predictions, rf_probabilities, "Random Forest")

# Put both models' results side-by-side in one neat table
comparison_table = pd.DataFrame([log_reg_results, rf_results]).set_index("Model")
print("\n=========== FINAL MODEL PERFORMANCE COMPARISON ===========")
print(comparison_table.round(3))
print("============================================================")

# ------------------------------------------------------------------------------
# STEP 11: CHART 1 - ATTRITION CLASS DISTRIBUTION
# ------------------------------------------------------------------------------
plt.figure(figsize=(6, 4))
sns.countplot(x=target_encoder.inverse_transform(y), hue=target_encoder.inverse_transform(y), palette="Set2", legend=False)
plt.title("Employee Attrition Distribution (500 sampled employees)")
plt.xlabel("Attrition (Did the employee leave?)")
plt.ylabel("Number of Employees")
plt.tight_layout()
plt.savefig("chart1_attrition_distribution.png")
plt.close()

# ------------------------------------------------------------------------------
# STEP 12: CHART 2 - CORRELATION HEATMAP (numeric features only)
# ------------------------------------------------------------------------------
plt.figure(figsize=(12, 9))
numeric_data = data.select_dtypes(include=np.number)
sns.heatmap(numeric_data.corr(), cmap="coolwarm", center=0, linewidths=0.3)
plt.title("Correlation Heatmap of Numeric Features")
plt.tight_layout()
plt.savefig("chart2_correlation_heatmap.png")
plt.close()

# ------------------------------------------------------------------------------
# STEP 13: CHART 3 - CONFUSION MATRICES (Logistic Regression vs Random Forest)
# ------------------------------------------------------------------------------
fig, axes = plt.subplots(1, 2, figsize=(11, 4.5))

cm_log = confusion_matrix(y_test, log_reg_predictions)
sns.heatmap(cm_log, annot=True, fmt="d", cmap="Blues",
            xticklabels=["Stayed", "Left"], yticklabels=["Stayed", "Left"], ax=axes[0])
axes[0].set_title("Logistic Regression - Confusion Matrix")
axes[0].set_xlabel("Predicted Label")
axes[0].set_ylabel("Actual Label")

cm_rf = confusion_matrix(y_test, rf_predictions)
sns.heatmap(cm_rf, annot=True, fmt="d", cmap="Greens",
            xticklabels=["Stayed", "Left"], yticklabels=["Stayed", "Left"], ax=axes[1])
axes[1].set_title("Random Forest - Confusion Matrix")
axes[1].set_xlabel("Predicted Label")
axes[1].set_ylabel("Actual Label")

plt.tight_layout()
plt.savefig("chart3_confusion_matrices.png")
plt.close()

# ------------------------------------------------------------------------------
# STEP 14: CHART 4 - ROC CURVE COMPARISON
# ------------------------------------------------------------------------------
plt.figure(figsize=(7, 6))

# Calculate the ROC curve points for each model
fpr_log, tpr_log, _ = roc_curve(y_test, log_reg_probabilities)
fpr_rf, tpr_rf, _ = roc_curve(y_test, rf_probabilities)

plt.plot(fpr_log, tpr_log, label=f"Logistic Regression (AUC = {log_reg_results['ROC-AUC']:.2f})", linewidth=2)
plt.plot(fpr_rf, tpr_rf, label=f"Random Forest (AUC = {rf_results['ROC-AUC']:.2f})", linewidth=2)
plt.plot([0, 1], [0, 1], linestyle="--", color="gray", label="Random Guess")  # baseline reference line

plt.title("ROC Curve Comparison")
plt.xlabel("False Positive Rate")
plt.ylabel("True Positive Rate")
plt.legend(loc="lower right")
plt.tight_layout()
plt.savefig("chart4_roc_curve_comparison.png")
plt.close()

# ------------------------------------------------------------------------------
# STEP 15: CHART 5 - SIDE-BY-SIDE METRIC COMPARISON (BAR CHART)
# ------------------------------------------------------------------------------
plt.figure(figsize=(9, 5.5))
plot_data = comparison_table.reset_index().melt(id_vars="Model", var_name="Metric", value_name="Score")
sns.barplot(data=plot_data, x="Metric", y="Score", hue="Model", palette="Set1")
plt.title("Model Performance Comparison")
plt.ylim(0, 1.05)
plt.ylabel("Score")
plt.axhline(0.80, linestyle="--", color="gray", linewidth=1)  # reference line at 80%
plt.legend(title="", loc="lower right")
plt.tight_layout()
plt.savefig("chart5_metric_comparison.png")
plt.close()

# ------------------------------------------------------------------------------
# STEP 16: CHART 6 - TOP 10 MOST IMPORTANT FEATURES (from Random Forest)
# ------------------------------------------------------------------------------
# Random Forest can tell us which features it relied on most when making
# predictions - this is a great way to understand WHY employees leave.
feature_importance = pd.Series(
    random_forest_model.feature_importances_, index=X_encoded.columns
).sort_values(ascending=False).head(10)

plt.figure(figsize=(8, 5.5))
sns.barplot(x=feature_importance.values, y=feature_importance.index, hue=feature_importance.index, palette="viridis", legend=False)
plt.title("Top 10 Most Important Features (Random Forest)")
plt.xlabel("Importance Score")
plt.tight_layout()
plt.savefig("chart6_feature_importance.png")
plt.close()

